"""Reproduce the v2 leaderboard from episode_decomposition.csv and write the distribution tables (audit).

    python <audit>/scripts/analyze.py --data <audit>/data --published <published leaderboard_v2.csv>

Writes <data>/reproduction_tables.md and <data>/distribution_tables.md; exits 1 on any reproduction mismatch.
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import statistics as st
from pathlib import Path

OVERRIDE_FAMILIES = ("override", "stressed-override")


def md(header, rows):
    out = ["| " + " | ".join(map(str, header)) + " |", "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|"]
    return "\n".join(out + ["| " + " | ".join(map(str, r)) + " |" for r in rows]) + "\n"


def load(data: Path):
    with (data / "episode_decomposition.csv").open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        r["seed"], r["credit"], r["weight"] = int(r["seed"]), float(r["credit"]), float(r["weight"])
    return rows


def families():
    """Scenario -> conflict family, from the published collector's own table."""
    import sys
    sys.path.insert(0, ".")
    from marshal_bench.criteria.marshal_metrics import CONFLICT_TYPE
    return dict(CONFLICT_TYPE)


def reproduce(lb, published):
    fam = families()
    W = {r["scenario"]: r["weight"] for r in lb}
    wsum = sum(W.values())
    out, problems = [], []
    pub = {r["model"]: r for r in published}
    for m in pub:
        cs = [r for r in lb if r["model"] == m]
        seeds = sorted({r["seed"] for r in cs})
        per = [100.0 * sum(r["weight"] * r["credit"] for r in cs if r["seed"] == s) / wsum for s in seeds]
        npass = [sum(r["strict"] == "PASS" for r in cs if r["seed"] == s) for s in seeds]
        mean, sd = st.mean(per), (st.stdev(per) if len(per) > 1 else None)
        ov = [r for r in cs if fam and fam.get(r["scenario"]) in OVERRIDE_FAMILIES]
        ov_txt = f"{sum(r['strict'] == 'PASS' for r in ov)}/{len(ov)}" if fam else "n/a"
        p = pub[m]
        checks = [("graded_mean", round(mean, 2), float(p["graded_mean"])),
                  ("strict_total", f"{sum(npass)}/{len(cs)}", p["strict_pass_total"]),
                  ("override", ov_txt, p["override_cells"])]
        if sd is not None:
            checks.append(("graded_sd", round(sd, 2), float(p["graded_sd"])))
        for k, mine, theirs in checks:
            if (abs(mine - theirs) > 0.005 if isinstance(mine, float) else str(mine) != str(theirs)):
                problems.append(f"{m} {k}: reproduced {mine} vs published {theirs}")
        out.append([m, len(seeds), len(cs), f"{mean:.4f}", "—" if sd is None else f"{sd:.4f}",
                    ";".join(f"{x:.4f}" for x in per), f"{sum(npass)}/{len(cs)}", ov_txt, p["graded_mean"],
                    p["graded_sd"] or "—", p["strict_pass_total"], p["override_cells"]])
    t = md(["model", "seeds", "episodes", "graded mean (repro)", "SD n−1 (repro)", "per-seed graded",
            "strict (repro)", "override (repro)", "graded (pub)", "SD (pub)", "strict (pub)", "override (pub)"], out)
    return t, problems, wsum


def crosstab(rows, by):
    c = collections.Counter((by(r), r["credit_class"]) for r in rows)
    keys = sorted({k for k, _ in c}, key=str)
    return md([" ", "full", "partial", "zero", "total"],
              [[k, c[(k, "full")], c[(k, "partial")], c[(k, "zero")],
                sum(c[(k, x)] for x in ("full", "partial", "zero"))] for k in keys])


def zero_flags(r):
    """Every zero-producing term of a zero-credit episode (overlapping)."""
    f = []
    if r["graded_invalid"] == "True":
        f.append("invalid")
    if r["movement_gate"] == "0":
        f.append("movement_gate")
    if float(r["action_credit"] or 0) == 0:
        f.append("action_credit")
    if float(r["latency_factor"] or 0) == 0:
        f.append("latency_factor")
    if float(r["safety_factor"] or 0) == 0:
        f.append("safety_factor")
    return f


def main() -> int:
    import sys
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--published", required=True)
    a = ap.parse_args()
    data = Path(a.data)
    rows = load(data)
    lb = [r for r in rows if r["cohort"] == "leaderboard"]
    with open(a.published, encoding="utf-8") as fh:
        published = list(csv.DictReader(fh))
    t_repro, problems, wsum = reproduce(lb, published)

    parts = ["# Reproduction (generated by analyze.py)\n",
             f"Leaderboard cohort: {len(lb)} episodes; weight sum Σw = {wsum}. Graded per run = 100·Σ w_s c_s / Σ w_s; "
             "mean over runs; SD = sample SD (n − 1) over the five VLM runs; published values rounded to 2 decimals.\n",
             t_repro, "\nMismatches: " + ("none" if not problems else "\n- " + "\n- ".join(problems)) + "\n"]
    (data / "reproduction_tables.md").write_text("\n".join(parts), encoding="utf-8")

    zeros = [r for r in lb if r["credit_class"] == "zero"]
    flags = [zero_flags(r) for r in zeros]
    combos = collections.Counter("+".join(f) or "(none)" for f in flags)
    single = collections.Counter(x for f in flags for x in f)
    excl = collections.Counter(next((x for x in ("invalid", "movement_gate", "action_credit", "latency_factor",
                                                 "safety_factor") if x in f), "(none)") for f in flags)
    beh = collections.Counter()
    for r in zeros:
        rs = (r["strict_reason"] or "").lower()
        beh[("collision" if "collision" in rs else "never engaged / no movement" if ("never engaged" in rs or "stationary" in rs)
             else "conflict-zone entry" if ("conflict" in rs or "intersection" in rs) else "detour incomplete"
             if ("blocked lane" in rs or "detour" in rs) else "other: " + rs[:70])] += 1
    out = ["# Distribution tables (generated by analyze.py)\n",
           f"Endpoint tolerance: credit ≥ 1 − 1e−6 is 'full', ≤ 1e−6 is 'zero' (stored credit is rounded to 6 decimals). "
           f"Exact endpoint check: full credits exactly 1.0 = {sum(r['credit'] == 1.0 for r in lb)}, "
           f"zero credits exactly 0.0 = {sum(r['credit'] == 0.0 for r in lb)}, smallest partial = "
           f"{min((r['credit'] for r in lb if r['credit_class'] == 'partial'), default=None)}, largest partial = "
           f"{max((r['credit'] for r in lb if r['credit_class'] == 'partial'), default=None)}.\n",
           "## Strict verdict × credit class (leaderboard, episode-weighted)\n", crosstab(lb, lambda r: r["strict"]),
           "## By expected action\n", crosstab(lb, lambda r: r["expected_action"]),
           "## By model\n", crosstab(lb, lambda r: r["model"]),
           "## By scenario\n", crosstab(lb, lambda r: r["scenario"]),
           "## Model-balanced shares (each model weight 1; VLM rows averaged over runs)\n",
           md(["class", "episode-weighted share", "model-balanced share"],
              [[k, f"{sum(r['credit_class'] == k for r in lb) / len(lb):.3f}",
                f"{st.mean(sum(r['credit_class'] == k for r in lb if r['model'] == m) / sum(r['model'] == m for r in lb) for m in sorted({r['model'] for r in lb})):.3f}"]
               for k in ("full", "partial", "zero")]),
           f"## Zero-credit episodes: every zero-producing term (overlapping), n = {len(zeros)}\n",
           md(["term", "episodes where it is 0"], single.most_common()),
           "## Zero-credit episodes: exact combinations of zero terms\n", md(["combination", "episodes"], combos.most_common()),
           "## Zero-credit episodes: exclusive classification (first zero term in the order invalid → movement gate → "
           "action credit → latency → safety)\n", md(["first zero term", "episodes"], excl.most_common()),
           "## Zero-credit episodes: behavioural label from the strict reason (not the mathematical cause)\n",
           md(["strict-reason label", "episodes"], beh.most_common()),
           "## Motion class (all leaderboard episodes)\n",
           md(["motion class", "STOP/HOLD", "PROCEED", "DETOUR", "YIELD", "total"],
              [[k, *[sum(r["motion_class"] == k and r["expected_action"] in acts for r in lb)
                     for acts in (("STOP", "HOLD"), ("PROCEED",), ("DETOUR",), ("YIELD",))],
                sum(r["motion_class"] == k for r in lb)] for k in sorted({r["motion_class"] for r in lb})]),
           "## Motion class × model\n",
           md(["model", *sorted({r["motion_class"] for r in lb})],
              [[m, *[sum(r["model"] == m and r["motion_class"] == k for r in lb) for k in sorted({r["motion_class"] for r in lb})]]
               for m in [p["model"] for p in published]])]
    (data / "distribution_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out)[:200])
    print("reproduction mismatches:", problems or "none")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
