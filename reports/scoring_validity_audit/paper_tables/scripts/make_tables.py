"""Paper-ready result tables from the generated audit outputs (offline; run from the audit checkout root).

    python reports/scoring_validity_audit/paper_tables/scripts/make_tables.py

Inputs (all generated elsewhere, read only):
  credit_v22_final/data/final_leaderboard.csv, final_leaderboard_sensitivity.csv, final_leaderboard_excluded.csv,
  credit_v22_final/final_leaderboard.md (F4 line), interfuser_remeasure/data/final_forward_suite_per_setup.csv,
  interfuser_greenstop/data/officer_vs_absent.csv.
Writes paper_tables/table_a_leaderboard.csv, table_b_interfuser_setups.csv, table_c_green_stop_control.csv and
paper_tables/paper_tables.md.
"""
import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
AUD = HERE.parents[1]
OUT = HERE.parent


def rd(p):
    return list(csv.DictReader(p.open(encoding="utf-8")))


def wr(name, rows):
    with (OUT / name).open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def num(cell):
    return float(str(cell).split(" ")[0])


lb = rd(AUD / "credit_v22_final/data/final_leaderboard.csv")
sens = {r["row"]: r for r in rd(AUD / "credit_v22_final/data/final_leaderboard_sensitivity.csv")}
excl = rd(AUD / "credit_v22_final/data/final_leaderboard_excluded.csv")
setups = rd(AUD / "interfuser_remeasure/data/final_forward_suite_per_setup.csv")
gs = rd(AUD / "interfuser_greenstop/data/officer_vs_absent.csv")
md_lb = (AUD / "credit_v22_final/final_leaderboard.md").read_text(encoding="utf-8")

# (a) leaderboard
ta = [{"rank": r["rank"], "model": r["model"], "runs": r["runs"], "strict_pass": r["strict_pass"],
       "credit_v22_final_mean": f"{float(r['graded']):.2f}", "sd": f"{float(r['sd']):.2f}",
       "min_max": f"{float(r['min']):.2f}–{float(r['max']):.2f}"} for r in lb]
wr("table_a_leaderboard.csv", ta)
hi = {r["model"]: float(r["graded"]) for r in lb}
up = sens["F3 upper bound (hidden contacts distinct)"]
lo = {m: num(up[m]) for m in hi if m in up}
names = [r["model"] for r in lb]
pairs = [(x, y) for i, x in enumerate(names) for y in names[i + 1:]
         if x in lo and y in lo and not (lo[x] > hi[y] or lo[y] > hi[x])]
geo = sens["without the 2 geometry scenarios"]
geo_changes = [f"{m} {r['rank']}→{geo[m].split('#')[1].rstrip(')')}" for m, r in ((r["model"], r) for r in lb)
               if m in geo and geo[m].split("#")[1].rstrip(")") != r["rank"]]
f2 = sens.get("F2 reference: best instruction-independent policy", {}).get("oracle", "")
f4 = next((ln.strip("- ").strip() for ln in md_lb.splitlines() if "outscores a 5 km/h creep" in ln), "").replace(" therefore", "")
gs_rank = [r for r in rd(AUD / "interfuser_remeasure/data/final_forward_green_stop.csv") if r["setup"] == "final-forward"]
ifr = next(r for r in lb if r["model"] == "InterFuser")

# (b) InterFuser setups
tb = [{"setup": r["setup"], "seeds": r["seeds"],
       "strict_pass_per_25": f"{float(r['strict_mean']):.2f} ({int(float(r['strict_min']))}–{int(float(r['strict_max']))})",
       "credit_v22_final": f"{float(r['v22_final_mean']):.2f} ± {float(r['v22_final_sd']):.2f} ({float(r['v22_final_min']):.2f}–{float(r['v22_final_max']):.2f})",
       "credit_v2": f"{float(r['v2_mean']):.2f} ± {float(r['v2_sd']):.2f} ({float(r['v2_min']):.2f}–{float(r['v2_max']):.2f})"}
      for r in setups]
wr("table_b_interfuser_setups.csv", tb)

# (c) green_stop control
tc = [{"condition": r["condition"], "seed": r["seed"], "travel_m": r["travel_m"], "v_max_kmh": r["v_max_kmh"],
       "final_front_to_line_m": r["final_front_to_line_m"], "first_brake_at_rest_s": r["first_brake_at_rest_s"],
       "brake_branch": f"{r['brake_branch']} ({r['zero_safe_distance_terms'].replace(';', ', ')})",
       "strict": r["strict"] or "–", "credit_v22_final": r["credit_v22_final"] or "–"} for r in gs]
wr("table_c_green_stop_control.csv", tc)

L = ["# Paper tables", "",
     "Generated by `scripts/make_tables.py` from the audit outputs; CSV versions next to this file.", "",
     "## (a) Leaderboard, Credit v2.2-final", "",
     "| rank | model | runs | strict PASS | Credit v2.2-final (mean ± SD) | range over runs |", "|---:|---|---:|---|---:|---|"]
L += [f"| {r['rank']} | {r['model']}{'ᵇ' if r['model'] == 'InterFuser' else ''} | {r['runs']} | {r['strict_pass']}"
      f"{'ᵃ' if r['strict_pass'].endswith('/125') else ''} | {r['credit_v22_final_mean']} ± {r['sd']} | {r['min_max']} |" for r in ta]
L += ["",
      "- ᵃ VLMs: 5 seeds × 25 scenarios = 125 episodes; every other model 1 seed × 25, except InterFuser.",
      f"- ᵇ InterFuser: {ifr['runs']} seeds (0, 1, 2) of the final adapter (original-agent sensor, route and control "
      "settings; forward speed input), 75 episodes. At `green_stop` the evidence supports a model-side pedestrian false "
      "positive (no checked adapter deviation explains it); its stop there is not distinguishable from a no-start (table c). "
      "In the ranked runs green_stop is " + ", ".join(f"s{r['seed']} {r['strict']} ({float(r['travel_m']):.2f} m)" for r in gs_rank)
      + "; a PASS there is a stop held by the same controller branch as the no-start (desired speed 0 at rest), not attributable to the officer.",
      "- F3 (contact identity after the 20th logged collision event): pairs whose scores are not separated by the "
      "contact-count bounds: " + (", ".join(f"{x}–{y}" for x, y in pairs) or "none") + ".",
      "- Geometry sensitivity (dropping `occluded_officer` and `sequential_directive`, whose lines are 2.5 m and 4.33 m "
      "from spawn): rank changes " + (", ".join(geo_changes) or "none") + ".",
      f"- F2 (trajectory credit cannot see whether the instruction was perceived): best instruction-independent "
      f"synthetic policy {f2}.",
      f"- F4 (speed ordering at equal overshoot): {f4}", ""]
for r in excl:
    L.append(f"- Not compared: {r['model']} — {r['status']}; strict {r['strict_pass']}, Credit v2.2-final "
             f"{r['graded_final']}{(' ± ' + r['sd_final']) if r.get('sd_final') else ''}.")
L += ["", "## (b) InterFuser adapter setups (25 scenarios × seeds 0–2 each)", "",
      "| setup | seeds | strict PASS /25, mean (range) | Credit v2.2-final, mean ± SD (range) | v2 credit, mean ± SD (range) |",
      "|---|---:|---|---|---|"]
L += [f"| {r['setup']} | {r['seeds']} | {r['strict_pass_per_25']} | {r['credit_v22_final']} | {r['credit_v2']} |" for r in tb]
L += ["", "- v2 setup: the protocol-v2 adapter configuration (leaderboard run s0 + re-runs s1, s2).",
      "- fixed-3d: original-agent LiDAR/camera attributes, LiDAR half-sweep alignment, 50 m route thinning, odd-step "
      "control hold; 3-D speed input.",
      "- final-forward: fixed-3d with the leaderboard forward-projected speed input (the ranked row).", "",
      "## (c) green_stop: officer present (STOP) vs absent (light frozen Green), final adapter", "",
      "| condition | seed | travel (m) | v_max (km/h) | front bumper to line (m) | first brake at rest (s) | brake branch | strict | Credit v2.2-final |",
      "|---|---:|---:|---:|---:|---:|---|---|---:|"]
L += [f"| {r['condition']} | {r['seed']} | {r['travel_m']} | {r['v_max_kmh']} | {r['final_front_to_line_m']} | "
      f"{r['first_brake_at_rest_s']} | {r['brake_branch']} | {r['strict']} | {r['credit_v22_final']} |" for r in tc]
L += ["", "- Separate runs from the ranked row, same final adapter settings; officer present seeds 0–2, absent seeds 0–4.",
      "- Absent, seed 2: braked at rest from 1.05 s, started at 1.55 s and reached 20 m past the line at 7.7 s.",
      "- Red-light probability 0.00 in every run. Source: `../interfuser_greenstop/paper_case_green_stop.md`.", ""]
(OUT / "paper_tables.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
